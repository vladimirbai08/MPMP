# Ця функція форматує температуру у виводі: 3 → 3.00 → 3°С, 5.333 → 5.33°С
def format_temp(t):
    return str(int(t)) if t.is_integer() else f"{t:.2f}"

for time, tt in my_dict.items():
    print(f"{time} → {format_temp(tt)}°С")

### TODO: вивести отримані числові значення статистичних показників
print("\nЗагальна кількість вимірювань:", n)
print(f"Середня температура: {format_temp(avg_t)}°С")
print(f"Максимальна температура: {format_temp(max_t)}°С")
print(f"Мінімальна температура: {format_temp(min_t)}°С")
print("Кількість додатних температур:", pos_count)
print("Кількість від’ємних температур:", neg_count)

# Виведення різких змін
### TODO: за утвореним списком з кортежів (час1, час2, різниця) вивести повідомлення про різкі зміни
if len(big_changes) > 0:
    print("\n[!] Виявлено різкі зміни температури (> 7°):")
    for t1, t2, diff in big_changes:
        print(f"між {t1} та {t2}: зміна на {format_temp(diff)}°С")
else:
    print("\nРізких змін температури не виявлено.")

