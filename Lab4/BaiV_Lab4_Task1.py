# task1_pipeline.py
from functools import reduce
from pprint import pprint

def main():
    # 1. Формування початкових даних (мінімум 5 записів)
    data = [
        {'Товар': 'Ноутбук', 'Кількість': 5, 'Ціна': 25000},
        {'Товар': 'Мишка', 'Кількість': 15, 'Ціна': 500},
        {'Товар': 'Клавіатура', 'Кількість': 12, 'Ціна': 1200},
        {'Товар': 'Монітор', 'Кількість': 8, 'Ціна': 7000},
        {'Товар': 'Навушники', 'Кількість': 20, 'Ціна': 1500},
    ]

    print("Початкові дані:")
    pprint(data)

    # 2. Фільтрація даних (Кількість > 10)
    filtered_data = list(
        filter(lambda x: x['Кількість'] > 10, data)
    )
    print("\nВідфільтровані дані (Кількість > 10):")
    pprint(filtered_data)

    # 3. Трансформація даних (Вартість партії = Кількість * Ціна)
    mapped_data = list(
        map(
            lambda x: {
                'Товар': x['Товар'],
                'Вартість партії': x['Кількість'] * x['Ціна']
            },
            filtered_data
        )
    )
    print("\nРозрахована вартість партій:")
    pprint(mapped_data)

    # 4. Агрегація даних (загальна сума)
    result = reduce(
        lambda acc, x: acc + x['Вартість партії'],
        mapped_data,
        0
    )
    print(f"\nЗагальна сума вартості всіх великих партій: {result} грн")


if __name__ == "__main__":
    main()