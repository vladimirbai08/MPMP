def find_jumps(data_dict, threshold):
    """Знаходить різкі перепади між сусідніми значеннями. Повертає список рядків із вказаними мітками часу та різницею."""
    ### TODO: пошук різких перепадів між сусідніми показами (функція може бути універсальною: застосовуватись для температури, вологості та тиску повітря) в аргументи передається словник з показами та порогове значення різниці; знайдені різниці записати у список (у вигляді кортежу: (часова_мітка_1, часова_мітка_2, значення_різниці), або у вигляді рядкового запису "T1 → T2: різнця"); функція має повертати словник (або пустий, або зі знайденими різницями)
    jumps = []
    keys = list(data_dict.keys())

    for i in range(len(keys) - 1):
        k1, k2 = keys[i], keys[i + 1]
        v1, v2 = data_dict[k1], data_dict[k2]
        diff = abs(v2 - v1)

        if diff > threshold:
            jumps.append(f"{k1} → {k2} ({diff:.2f})")

    return jumps

